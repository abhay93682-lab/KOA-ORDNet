"""Evaluate trained checkpoints and fill the paper's Table II / Table III from real runs.

    python evaluate.py --data data/kneeKL224 --runs runs/koa_ordnet [--external data/external_koa]

Writes results/results.json and results/RESULTS.md. Numbers come only from the
checkpoints you trained; nothing is filled in by hand.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader

from koa_ordnet.data import KneeDataset, list_split
from koa_ordnet.gradcam import GradCAM, cam_iou
from koa_ordnet.metrics import compute_metrics
from koa_ordnet.model import KOAOrdNet
from train import predict

NAMES = {"ce": "ResNet-50 + Cross-Entropy (baseline)",
         "ordinal": "ResNet-50 + Ordinal Loss (Chen-style, reproduced)",
         "koa": "KOA-ORDNet (proposed)"}


def load(ckpt, device):
    c = torch.load(ckpt, map_location=device)
    m = KOAOrdNet(head=c["head"], pretrained=False)
    m.load_state_dict(c["state_dict"])
    return m.to(device).eval(), c["head"]


def gradcam_iou(model, items, device, per_grade=20, seed=0):
    """Mean Grad-CAM IoU on a stratified sample (up to per_grade images per KL grade)."""
    rng = np.random.default_rng(seed)
    sample = []
    for g in range(5):
        gi = [it for it in items if it[1] == g]
        if gi:
            idx = rng.choice(len(gi), size=min(per_grade, len(gi)), replace=False)
            sample += [gi[i] for i in idx]
    ds, cam = KneeDataset(sample), GradCAM(model, model.target_layer)
    ious = []
    for i in range(len(ds)):
        x, _ = ds[i]
        c, _ = cam(x.unsqueeze(0).to(device))
        ious.append(cam_iou(c))
    cam.remove()
    return float(np.mean(ious)), len(ious)


def main(a):
    device = "cuda" if torch.cuda.is_available() else "cpu"
    test_items = list_split(a.data, "test", a.limit_per_class)
    ext_items = list_split(a.external, None, a.limit_per_class) if a.external else None
    results = {}

    def best_val_f1(run_dir: Path) -> float:
        h = run_dir / "history.json"
        return max(e["macro_f1"] for e in json.loads(h.read_text())) if h.exists() else -1.0

    # KOA-ORDNet model selection uses the VALIDATION set only: among runs/koa* (e.g. different
    # focal gamma), the run with the best validation macro-F1 is the one evaluated on test.
    koa_runs = sorted(d for d in Path(a.runs).glob("koa*") if (d / "best.pt").exists())
    selection = {d.name: best_val_f1(d) for d in koa_runs}
    koa_dir = max(koa_runs, key=best_val_f1).name if koa_runs else "koa"
    if selection:
        print("KOA-ORDNet runs (best val macro-F1):", selection, "-> selected", koa_dir)

    for key, run in (("ce", "ce"), ("ordinal", "ordinal"), ("koa", koa_dir)):
        ckpt = Path(a.runs) / run / "best.pt"
        if not ckpt.exists():
            print(f"skip {key}: {ckpt} not found")
            continue
        model, head = load(ckpt, device)
        dl = lambda items: DataLoader(KneeDataset(items), batch_size=32, num_workers=a.workers)
        r = {"in_distribution": compute_metrics(*predict(model, dl(test_items), head, device))}
        if ext_items:
            r["out_of_distribution"] = compute_metrics(*predict(model, dl(ext_items), head, device))
        r["gradcam_iou"], r["gradcam_n"] = gradcam_iou(model, test_items, device)
        r["run"], r["best_val_macro_f1"] = run, best_val_f1(Path(a.runs) / run)
        if key == "koa":
            r["koa_val_selection"] = selection
        results[key] = r
        print(key, json.dumps({k: r["in_distribution"][k] for k in ("accuracy", "macro_f1", "qwk", "mae", "grade34_recall")}))

    out = Path("results"); out.mkdir(exist_ok=True)
    (out / "results.json").write_text(json.dumps(results, indent=2))

    lines = ["# Results (generated by evaluate.py)", "", "## Table II - In-distribution test", "",
             "| Model | Acc. | Macro-F1 | QWK | MAE | Grade 3-4 Recall | Grad-CAM IoU |",
             "|---|---|---|---|---|---|---|"]
    for k, r in results.items():
        d = r["in_distribution"]
        lines.append(f"| {NAMES[k]} | {d['accuracy']*100:.2f}% | {d['macro_f1']:.4f} | {d['qwk']:.4f} | "
                     f"{d['mae']:.4f} | {d['grade34_recall']*100:.2f}% | {r['gradcam_iou']:.3f} |")
    if ext_items and "koa" in results:
        i, o = results["koa"]["in_distribution"], results["koa"]["out_of_distribution"]
        lines += ["", "## Table III - Cross-dataset generalization (KOA-ORDNet)", "",
                  "| Test set | Accuracy | QWK |", "|---|---|---|",
                  f"| In-distribution | {i['accuracy']*100:.2f}% | {i['qwk']:.4f} |",
                  f"| Out-of-distribution | {o['accuracy']*100:.2f}% | {o['qwk']:.4f} |"]
    (out / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("wrote results/results.json and results/RESULTS.md")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/kneeKL224")
    ap.add_argument("--runs", default="runs/koa_ordnet")
    ap.add_argument("--external", default=None, help="external dataset root with 0..4 folders")
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--limit-per-class", type=int, default=None)
    main(ap.parse_args())
